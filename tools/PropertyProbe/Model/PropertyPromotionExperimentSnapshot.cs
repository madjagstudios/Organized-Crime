    string DocksWarehouseCodeAfter,
    bool DocksWarehouseOwnedBefore,
    bool DocksWarehouseOwnedAfter,
    string? FailureReason)
{
    public static PropertyPromotionExperimentSnapshot Test(
        string gate = "preconditions",
        bool preconditionsPassed = false,
        bool registrationPassed = false,
        bool ownershipPassed = false,
        bool persistencePassed = false,
