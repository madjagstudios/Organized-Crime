        int ownedPropertyCountAfter = 0,
        int unownedPropertyCountBefore = 0,
        int unownedPropertyCountAfter = 0,
        bool targetRegisteredAfter = false,
        bool targetOwnedAfter = false,
        bool targetInOwnedCollectionAfter = false,
        bool targetInUnownedCollectionAfter = false,
